// UI strings for both languages. Page-level copy lives in the pages and the
// content collection; this file holds the shared interface vocabulary.
export type Lang = 'en' | 'de';

export const langPrefix = (lang: Lang) => (lang === 'de' ? '/de' : '');

// Given the current path, the equivalent path in the other language.
export const altPath = (path: string, target: Lang) => {
  const bare = path.startsWith('/de') ? path.replace(/^\/de/, '') || '/' : path;
  return target === 'de' ? (bare === '/' ? '/de/' : `/de${bare}`) : bare;
};

